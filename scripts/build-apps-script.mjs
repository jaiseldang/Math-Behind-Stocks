/**
 * Build the Google Apps Script version of Portfolio Explorer.
 *
 *   npm run build:gas
 *
 * Produces three files in apps-script/dist/ to paste into an Apps Script project:
 *   Code.gs          the backend (API + data fetching + cache), from apps-script/src/server.ts
 *   Index.html       the whole website in one file, from apps-script/src/client.tsx
 *   appsscript.json  the project manifest (V8 runtime, web app settings)
 *
 * Both are bundled from the same source code as the Next.js site.
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "apps-script/dist");
const shim = (f) => path.join(root, "apps-script/src/shims", f);

/**
 * Point some imports at small stand-ins in apps-script/src/shims:
 *  - next/link, next/navigation → a hash router (an Apps Script web app is one page)
 *  - katex → the copy loaded from the CDN (saves ~260 KB)
 *  - d3 → only the four d3 modules the charts use (saves ~30 KB)
 */
const shims = {
  name: "shims",
  setup(b) {
    b.onResolve({ filter: /^next\/link$/ }, () => ({ path: shim("next-link.tsx") }));
    b.onResolve({ filter: /^next\/navigation$/ }, () => ({ path: shim("next-navigation.ts") }));
    b.onResolve({ filter: /^katex$/ }, (a) => (a.importer.endsWith("katex.ts") ? undefined : { path: shim("katex.ts") }));
    b.onResolve({ filter: /^d3$/ }, () => ({ path: shim("d3.ts") }));
  },
};

/** Static website: answer /api/ calls in the browser instead of via google.script.run. */
const localApi = {
  name: "local-api",
  setup(b) {
    b.onResolve({ filter: /shims\/fetch-bridge$/ }, () => ({ path: shim("fetch-local.ts") }));
  },
};

const common = {
  bundle: true,
  write: false,
  absWorkingDir: root,
  tsconfig: path.join(root, "apps-script/tsconfig.json"),
  loader: { ".json": "json" },
  legalComments: "none",
  logLevel: "warning",
};

export async function buildServer() {
  const r = await build({
    ...common,
    entryPoints: ["apps-script/src/server.ts"],
    format: "iife",
    globalName: "PortfolioExplorer",
    platform: "neutral",
    target: "es2019", // Apps Script's V8 runtime
    minify: false,
  });
  const header = `/**
 * Portfolio Explorer: Google Apps Script backend.
 * GENERATED by "npm run build:gas" from apps-script/src/server.ts. Edit the source, not this file.
 *
 * Setup: see apps-script/README.md. In short: paste this as Code.gs, add Index.html,
 * set FRED_API_KEY under Project Settings → Script Properties, then Deploy → New deployment → Web app.
 */

// Small polyfills in case the runtime lacks them.
if (!Array.prototype.at) Object.defineProperty(Array.prototype, "at", { value: function (i) { i = Math.trunc(i) || 0; if (i < 0) i += this.length; return this[i]; }, configurable: true, writable: true });
if (!Object.fromEntries) Object.fromEntries = function (it) { var o = {}; for (var p of it) o[p[0]] = p[1]; return o; };

`;
  const footer = `

// Entry points Apps Script looks for (they must be top-level functions).
function doGet(e) { return PortfolioExplorer.doGet(e); }
function doPost(e) { return PortfolioExplorer.doPost(e); }
function handleApi(method, url, body) { return PortfolioExplorer.handleApi(method, url, body); }
function serviceUrl() { return PortfolioExplorer.serviceUrl(); }
/** Run from the editor to check that every data source works (see the execution log). */
function testSources() { return PortfolioExplorer.testSources(); }
/** Run from the editor to force fresh downloads. */
function clearCache() { return PortfolioExplorer.clearCache(); }
`;
  return header + r.outputFiles[0].text + footer;
}

export async function buildClient() {
  const { js, css, katexVersion } = await bundleClient("gas");
  const themeScript = `try{var t=JSON.parse(localStorage.getItem("pe.theme"));if(t==="light"||t==="dark")document.documentElement.setAttribute("data-theme",t)}catch(e){}`;
  return `<!DOCTYPE html>
<!-- Portfolio Explorer: the whole website in one file. GENERATED by "npm run build:gas"; edit the source in app/, components/ and lib/, not this file. -->
<html lang="en">
<head>
<meta charset="utf-8">
<script>${themeScript}</script>
<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@${katexVersion}/dist/katex.min.css">
<script src="https://cdn.jsdelivr.net/npm/katex@${katexVersion}/dist/katex.min.js"></script>
<style>${css}</style>
</head>
<body>
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;
}

/**
 * The hosted single-page website (static/index.html): no server at all. The
 * "API" runs in the browser on the snapshot, KaTeX's stylesheet and fonts
 * are embedded, and download buttons are hidden (the host blocks downloads).
 * The host wraps the page in <html>/<head>/<body>, so we don't write them.
 */
export async function buildStatic() {
  const { js, css, katexVersion } = await bundleClient("static");
  const katexDir = path.join(root, "node_modules/katex/dist");
  const katexCss = readFileSync(path.join(katexDir, "katex.min.css"), "utf8")
    .replace(/,url\(fonts\/[^)]+\.(woff|ttf)\) format\("[a-z]+"\)/g, "")
    .replace(/url\(fonts\/([^)]+\.woff2)\)/g, (_, f) => `url(data:font/woff2;base64,${readFileSync(path.join(katexDir, "fonts", f)).toString("base64")})`);
  // Sticky bars must clear the phone's safe-area inset on the host.
  const hostCss = `.mobile-bar{top:env(safe-area-inset-top,0px)}.sidebar{top:env(safe-area-inset-top,0px)}`;
  return `<title>Portfolio Explorer</title>
<!-- Portfolio Explorer, hosted single-page version. GENERATED by "npm run build:static"; edit the source in app/, components/ and lib/, not this file. -->
<style>${katexCss}</style>
<style>${css}${hostCss}</style>
<script src="https://cdn.jsdelivr.net/npm/katex@${katexVersion}/dist/katex.min.js"></script>
<div id="root"></div>
<script>${js}</script>
`;
}

async function bundleClient(target) {
  const r = await build({
    ...common,
    entryPoints: ["apps-script/src/client.tsx"],
    outdir: "out", // required for the CSS output; nothing is written
    format: "iife",
    platform: "browser",
    target: "es2020",
    jsx: "automatic",
    minify: true,
    define: { "process.env.NODE_ENV": '"production"', "process.env.NEXT_PUBLIC_PE_TARGET": JSON.stringify(target) },
    plugins: target === "static" ? [localApi, shims] : [shims],
    // Preact is a 10 KB drop-in for React (saves ~200 KB); the pages don't change.
    alias: { react: "preact/compat", "react-dom": "preact/compat", "react-dom/client": "preact/compat/client", "react/jsx-runtime": "preact/jsx-runtime" },
  });
  const js = r.outputFiles.find((f) => f.path.endsWith(".js")).text;
  const css = r.outputFiles.find((f) => f.path.endsWith(".css")).text;
  const katexVersion = JSON.parse(readFileSync(path.join(root, "node_modules/katex/package.json"), "utf8")).version;
  // "</script" inside the bundle would end the <script> tag early.
  return { js: js.replace(/<\/script/gi, "<\\/script"), css, katexVersion };
}

export const manifest = {
  timeZone: "Etc/UTC",
  runtimeVersion: "V8",
  exceptionLogging: "STACKDRIVER",
  oauthScopes: ["https://www.googleapis.com/auth/script.external_request"],
  webapp: { executeAs: "USER_DEPLOYING", access: "ANYONE_ANONYMOUS" },
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url) && process.argv[2] === "--static") {
  mkdirSync(path.join(root, "static"), { recursive: true });
  const page = await buildStatic();
  writeFileSync(path.join(root, "static/index.html"), page);
  console.log(`static/index.html                 ${(Buffer.byteLength(page) / 1024).toFixed(0)} KB`);
} else if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(out, { recursive: true });
  const [server, client] = await Promise.all([buildServer(), buildClient()]);
  writeFileSync(path.join(out, "Code.gs"), server);
  writeFileSync(path.join(out, "Index.html"), client);
  writeFileSync(path.join(out, "appsscript.json"), JSON.stringify(manifest, null, 2) + "\n");
  const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
  console.log(`apps-script/dist/Code.gs          ${kb(server)}`);
  console.log(`apps-script/dist/Index.html       ${kb(client)}`);
  console.log(`apps-script/dist/appsscript.json`);
}
